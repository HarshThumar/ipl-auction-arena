"""Replay the real 2022-2026 auctions through the engine from the recorded outcomes.

Run:  python scripts/replay_auctions.py
Writes docs/replay-report.md and data/processed/replay/replay_<season>.json (no timestamps: the files
only change when the result changes). Exit code 1 if any season has a problem.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src.engine.replay import SEASONS, replay_season  # noqa: E402

OUT_DIR = ROOT / "data" / "processed" / "replay"
REPORT = ROOT / "docs" / "replay-report.md"


def crore(lakh: int) -> str:
    return f"{lakh / 100:.2f}".rstrip("0").rstrip(".") if lakh % 100 else f"{lakh // 100}"


def reconciliation_text(rc: dict) -> str:
    if not rc:
        return ""
    calls = rc["lot_order_ordered_calls"] + rc["lot_order_unordered_rows"]
    two_rows = rc["master_rows"] - rc["master_players"]
    t = (f"{rc['lot_order_rows']} rows in lot_order.csv"
         + (f" + {rc['names_split_from_one_row']} extra names that share a row (\"A and B\")" if rc["names_split_from_one_row"] else "")
         + f" = {calls} calls; {rc['repeat_calls']} of them are repeat calls of a player already called "
         f"(accelerated rounds), so {calls - rc['repeat_calls']} distinct players. "
         f"The master has {rc['master_rows']} rows = {rc['master_players']} players + {two_rows} players with two rows "
         f"(one unsold row, one sold row). {rc['master_players_not_in_lot_order']} master player(s) were never narrated "
         f"and are placed by set number or appended.")
    if rc["sold_calls_inferred"]:
        t += (f" {rc['sold_calls_inferred']} sold players only show unsold calls in lot_order.csv; their sale is added "
              f"as a later call after the last narrated lot (accelerated round, not narrated).")
    return t


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    reps = []
    for y in SEASONS:
        r = replay_season(y)
        reps.append(r)
        (OUT_DIR / f"replay_{y}.json").write_text(json.dumps(r.to_dict(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"{y}: {'OK' if r.ok else 'PROBLEMS'}  lots {r.lots}  sold {r.sold}/{r.official_sold}  "
              f"hammer {crore(r.hammer_total_lakh)} cr  exact {r.outcomes_exact}/{r.lots}  problems {len(r.problems)}")
        for p in r.problems:
            print("   ", p)
    L = ["# Replay of the real 2022-2026 auctions", "",
         "Generated by `python scripts/replay_auctions.py` (engine: `src/engine/replay.py`). This is the L1 gate item",
         "\"replays the real 2022-2026 auctions from the recorded outcomes with zero rule violations\".", "",
         "**What this is:** an *outcome* replay, not a bid-by-bid replay. For each recorded lot, in calling order, two code",
         "bidders are set up so the engine has to produce the recorded winner at the recorded hammer price (unsold lots get no",
         "bidder). The engine then enforces purse, squad, overseas, ladder and max-legal-bid rules on its own. The recorded",
         "runner-up is not known for most lots, so a team that could legally have bid is used (the recorded final two when",
         "there is one).", "",
         "**What it proves:** every recorded result is *legal* under our rules, in an order consistent with the sources. It does",
         "not prove our room would produce these prices without being forced to.", "",
         "Inputs (committed data only): `pre_auction_state/<season>.json`, `master/all_auctions_master.json`,",
         "`auction_order/replay_order.csv` (built locally by `scripts/build_replay_order.py`), rules in `data/reference/`.", "",
         "## Result", "",
         "| Season | Lots called | Sold (engine / official) | Hammer, crore (engine / official) | Outcomes exact | Final squad min-max | Max overseas | Problems |",
         "|---|---|---|---|---|---|---|---|"]
    for r in reps:
        L.append(f"| {r.season} | {r.lots} | {r.sold} / {r.official_sold} | {crore(r.hammer_total_lakh)} / {crore(r.official_hammer_lakh)} "
                 f"| {r.outcomes_exact} / {r.lots} | {r.min_squad}-{r.max_squad} | {r.max_overseas} | {len(r.problems)} |")
    L += ["", "Every season is also checked for: purse >= 0, squad <= 25 and overseas <= 8 after every lot (live and again from the event log),",
          "every bid on the grid path from the base price and within the bidder's maximum legal bid, and 18 to 25 players per team at the end.", ""]
    for r in reps:
        L += [f"## {r.season}", "",
              f"- Lots called: {r.lots}; sold {r.sold}; unsold {r.unsold}. Event log: {r.log_events} events, SHA-256 `{r.log_digest[:16]}...` (seed {r.seed}).",
              "- Order basis of the lots: " + ", ".join(f"{k} {v}" for k, v in sorted(r.order_basis.items())) + ".",
              f"- Lot-count reconciliation: {reconciliation_text(r.reconciliation)}"]
        if r.alt_grid_lots:
            L.append(f"- Step grid: {len(r.alt_grid_lots)} sold lot(s) are on the other grid than the season's default (25-lakh steps above 5 cr, "
                     f"or 20-lakh where the default is 25): " + ", ".join(r.alt_grid_lots[:60]) + ("..." if len(r.alt_grid_lots) > 60 else "") + ".")
        if r.moves:
            L.append("- Order moves (position inside the unordered block is unknown): " + "; ".join(r.moves) + ".")
        for n in r.notes:
            L.append(f"- {n}")
        if r.problems:
            L += ["", "**Problems:**", ""] + [f"- {p}" for p in r.problems]
        else:
            L.append("- Problems: none.")
        L.append("")
    L += ["## Limits (read before quoting this)", "",
          "- **Order.** Calling order is exact across sets for lots a live blog narrated; lots it did not narrate are placed by their set",
          "  number (exact across sets, approximate inside a set). 2024 has only 37 narrated lots of 83. Sets above the main-phase cut are",
          "  really accelerated-round nominations, so their set number does not give their true position; where a recorded sale is not",
          "  legal at its set position, the lot is moved earlier (listed above) and never before the last narrated lot.",
          "- **Step grid.** Above 3 cr the auctioneer chooses the step (BCCI: minimum 20 lakh). Recorded prices need both 20-lakh and",
          "  25-lakh steps, so a lot whose hammer is not on the season's default grid is replayed on the other one (listed above).",
          "- **Runner-up and RTM.** The runner-up is chosen, not recorded. 2025 RTM sales are replayed as ordinary sales to the recorded",
          "  final owner (no RTM card is used in the replay), so RTM card counts are not exercised here.",
          "- **Money.** Hammer totals match the official figures; the purse is charged the hammer, and the 2026 Cameron Green lot is paid 1800 lakh.",
          ""]
    REPORT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}")
    return 0 if all(r.ok for r in reps) else 1


if __name__ == "__main__":
    sys.exit(main())
