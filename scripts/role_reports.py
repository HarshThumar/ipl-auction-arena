"""Cross-checks on the role labels (step 4 of docs/needs-plan.md).

1. Source agreement: data vs Wikipedia vs auction list, per main role (coarse: all-rounders merged).
2. Stability: how often a player's label flips between consecutive seasons. Some flips are real
   (a batter who starts bowling); a high flip rate in one field means the rule is too twitchy.
3. Hand-check sheet: a fixed random sample of 100 player-seasons with an ESPNcricinfo profile
   link, for a person to tick right/wrong. Links only; nothing is fetched from ESPNcricinfo.

Output: docs/roles-check.md and data/processed/roles/handcheck_sample.csv
Run:    python scripts/role_reports.py
"""
import csv, random, sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data" / "processed"
REPORT = ROOT / "docs" / "roles-check.md"
SHEET = PROC / "roles" / "handcheck_sample.csv"
coarse = lambda m: "allrounder" if m.startswith("allrounder") else m


def main():
    rows = list(csv.DictReader(open(PROC / "roles" / "player_roles.csv", encoding="utf-8")))
    wiki = {r["cricsheet_id"]: r for r in csv.DictReader(open(PROC / "roles" / "wiki_profiles.csv", encoding="utf-8"))}
    L = ["# Role labels: cross-checks", "", "Generated by `scripts/role_reports.py` from "
         "`data/processed/roles/player_roles.csv`.", ""]

    # 1. agreement
    L += ["## 1. Do the sources agree? (main role, all-rounder kinds merged)", "",
          "| pair | both present | agree |", "|---|---|---|"]
    for a, b in (("main_data", "main_wiki"), ("main_data", "main_auction"), ("main_wiki", "main_auction")):
        both = [r for r in rows if r[a] and r[b]]
        ag = sum(coarse(r[a]) == coarse(r[b]) for r in both)
        L.append(f"| {a[5:]} vs {b[5:]} | {len(both)} | {100 * ag / max(1, len(both)):.1f}% |")
    dis = Counter((coarse(r["main_data"]), coarse(r["main_wiki"])) for r in rows
                  if r["main_data"] and r["main_wiki"] and coarse(r["main_data"]) != coarse(r["main_wiki"]))
    L += ["", "Most common data-vs-Wikipedia disagreements (data first):", ""]
    L += [f"- {d} vs {w}: {n}" for (d, w), n in dis.most_common(6)]
    L += ["", "Most are borderline cases (a batter who bowls a few overs; a bowler Wikipedia calls an",
          "all-rounder). Data wins when it has 10+ matches, because it shows what the player did in",
          "the last three years, not his career label.", ""]

    # 2. stability
    by_player = defaultdict(list)
    for r in rows:
        if r["cricsheet_id"]:
            by_player[r["cricsheet_id"]].append(r)
    L += ["## 2. Stability between consecutive seasons", "", "| field | pairs | flips |", "|---|---|---|"]
    for f in ("main_role", "bat_subtype", "bowl_type", "bowl_phase"):
        pairs = flips = 0
        for rs in by_player.values():
            seen = {}
            for r in rs:
                seen[int(r["season"])] = r[f]
            for y in seen:
                if y + 1 in seen and seen[y] not in ("", "unknown") and seen[y + 1] not in ("", "unknown"):
                    pairs += 1
                    flips += seen[y] != seen[y + 1]
        L.append(f"| {f} | {pairs} | {100 * flips / max(1, pairs):.1f}% |")
    L += ["", "bowl_type should almost never flip (it comes from one Wikipedia field); a flip there is a",
          "bug. Phase and batting position flip more because they follow what the player actually did.", ""]

    # 3. hand-check sheet
    rng = random.Random(2026)
    pool = [r for r in rows if r["cricsheet_id"]]
    sample = sorted(rng.sample(pool, 100), key=lambda r: (r["season"], r["team"], r["player"]))
    SHEET.parent.mkdir(parents=True, exist_ok=True)
    with open(SHEET, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["season", "team", "player", "main_role", "bat_subtype", "bowl_type", "bowl_phase",
                    "confidence", "espncricinfo_link", "correct_y_n", "note"])
        for r in sample:
            ci = wiki.get(r["cricsheet_id"], {}).get("cricinfo_id", "")
            link = f"https://www.espncricinfo.com/cricketers/player-{ci}" if ci else ""
            w.writerow([r["season"], r["team"], r["player"], r["main_role"], r["bat_subtype"], r["bowl_type"],
                        r["bowl_phase"], r["confidence"], link, "", ""])
    L += ["## 3. Hand check", "", f"`{SHEET.relative_to(ROOT).as_posix()}`: 100 random player-seasons "
          "(seed 2026) to mark right or wrong. Not yet filled in.", ""]
    REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
